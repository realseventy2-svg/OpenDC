static int s_current_page = 0;
static volatile uint16_t *s_draw_fb = (volatile uint16_t *)VRAM_PAGE_0;

void video_init(void) {
    PVR_VIDEO_CFG     = 0x00000008;
    PVR_BORDER_COLOR  = 0x00000000;

    PVR_BORDER_X      = 0x007E0345;
    PVR_BORDER_Y      = 0x00240204;
    PVR_SCAN_CLK      = 0x020C0359;
    PVR_IL_CFG        = 0x00000100;
    PVR_BITMAP_X      = 0x000000AC;
    PVR_BITMAP_Y      = 0x00280028;
    PVR_SCALER_CFG    = 0x00000400;

    PVR_FB_ADDR       = 0x00000000;
    PVR_FB_IL_ADDR    = 0x00000000;
    PVR_FB_CFG_1      = 0x00800005;
    PVR_FB_CFG_2      = 0x00000009;
    PVR_RENDER_MODULO = 160;
    PVR_FB_SIZE       = (1 << 20) | (479 << 10) | 319;

    PVR_VIDEO_CFG     = 0x00000000;

    s_current_page    = 0;
    s_draw_fb         = (volatile uint16_t *)VRAM_PAGE_0;
}

void video_wait_vblank(void) {
    /* 1. If currently in VBlank (scanline >= 480), wait until active scanout begins */
    while ((PVR_SYNC_STATUS & 0x03FF) >= 480) { }

    /* 2. Wait until active scanout completes and next VBlank begins */
    while ((PVR_SYNC_STATUS & 0x03FF) < 480) { }
}

void video_wait_seconds(int seconds) {
    int total_vblanks = seconds * 60;
    for (int i = 0; i < total_vblanks; i++) {
        video_wait_vblank();
    }
}

void video_set_target_buffer(uint32_t addr) {
    s_draw_fb = (volatile uint16_t *)addr;
}

uint32_t video_get_current_fb(void) {
    return (s_current_page == 0) ? VRAM_PAGE_0 : VRAM_PAGE_1;
}

uint32_t video_get_back_fb(void) {
    return (s_current_page == 0) ? VRAM_PAGE_1 : VRAM_PAGE_0;
}

void video_flip_buffer(void) {
    /* 1. Wait for cathode ray / rasterizer to enter vertical blanking */
    video_wait_vblank();

    /* 2. Atomic swap of displayed surface */
    s_current_page ^= 1;
    uint32_t fb_offset = (s_current_page == 0) ? 0x00000000UL : 0x00100000UL;
    PVR_FB_ADDR    = fb_offset;
    PVR_FB_IL_ADDR = fb_offset;

    /* 3. Update drawing pointer to point to the inactive back buffer */
    s_draw_fb = (s_current_page == 0) ? (volatile uint16_t *)VRAM_PAGE_1 : (volatile uint16_t *)VRAM_PAGE_0;
}

void video_sync_buffers(void) {
    volatile uint32_t *src = (volatile uint32_t *)video_get_current_fb();
    volatile uint32_t *dst = (volatile uint32_t *)video_get_back_fb();
    for (size_t i = 0; i < (SCREEN_WIDTH * SCREEN_HEIGHT * 2) / 4; i++) {
        dst[i] = src[i];
    }
}

void video_clean_handoff(void) {
    /* 1. Reset PowerVR Tile Accelerator (TA) and Core graphics pipelines */
    *(volatile uint32_t *)(PVR_BASE + 0x0008) = 0x00000003;
    for (volatile int i = 0; i < 0x2000; i++) {
        __asm__ volatile("nop");
    }
    *(volatile uint32_t *)(PVR_BASE + 0x0008) = 0x00000000;

    /* 2. Reset ISP/TSP Depth, Culling, Punch-Through & Blanking registers */
    *(volatile uint32_t *)(PVR_BASE + 0x0078) = 0x00000000; /* FPU_CULL_VAL */
    *(volatile uint32_t *)(PVR_BASE + 0x007C) = 0x00000000; /* FPU_PARAM_CFG */
    *(volatile uint32_t *)(PVR_BASE + 0x0080) = 0x00000000; /* HALF_OFFSET */
    *(volatile uint32_t *)(PVR_BASE + 0x0084) = 0x00000000; /* FPU_PERP_VAL */
    *(volatile uint32_t *)(PVR_BASE + 0x0088) = 0x00000000; /* ISP_BACKGND_D (W_ZERO depth scale) */
    *(volatile uint32_t *)(PVR_BASE + 0x008C) = 0x3F800000; /* ISP_BACKGND_T (Z_CLIP: 1.0f float) */
    *(volatile uint32_t *)(PVR_BASE + 0x0098) = 0x00000000; /* ISP_FEED_CFG (Translucent sort) */
    *(volatile uint32_t *)(PVR_BASE + 0x00C8) = 0x00000000; /* SPG_HBLANK_INT */
    *(volatile uint32_t *)(PVR_BASE + 0x00CC) = 0x00000000; /* SPG_VBLANK_INT */
    *(volatile uint32_t *)(PVR_BASE + 0x011C) = 0x00000000; /* PT_ALPHA_REF (Punch-Through Alpha Ref) */

    /* 3. Set framebuffer to clean frosty white baseline for seamless BIOS handoff */
    uint32_t white32 = ((uint32_t)RGB565(248, 250, 254) << 16) | (uint32_t)RGB565(248, 250, 254);
    volatile uint32_t *vram = (volatile uint32_t *)VRAM_BASE;
    for (size_t i = 0; i < (640 * 480 * 2) / 4; i++) {
        vram[i] = white32;
    }

    /* 4. Reset primary video display registers to clean Katana baseline */
    PVR_FB_ADDR       = 0x00000000;
    PVR_FB_IL_ADDR    = 0x00000000;
    PVR_BORDER_COLOR  = 0x00000000;
    s_current_page    = 0;
    s_draw_fb         = (volatile uint16_t *)VRAM_PAGE_0;
}

void video_clear(uint16_t color) {
    volatile uint16_t *fb = s_draw_fb;
    for (int i = 0; i < SCREEN_WIDTH * SCREEN_HEIGHT; i++) {
        fb[i] = color;
    }
}

void video_fill_rect(int x, int y, int w, int h, uint16_t color) {
    volatile uint16_t *fb = s_draw_fb;
    for (int row = y; row < y + h; row++) {
        if ((unsigned)row >= SCREEN_HEIGHT) continue;
        volatile uint16_t *line = fb + (row * SCREEN_WIDTH) + x;
        for (int col = 0; col < w; col++) {
            if ((unsigned)(x + col) >= SCREEN_WIDTH) continue;
            line[col] = color;
        }
    }
}

void video_draw_pixel(int x, int y, uint16_t color) {
    if ((unsigned)x < SCREEN_WIDTH && (unsigned)y < SCREEN_HEIGHT) {
        s_draw_fb[y * SCREEN_WIDTH + x] = color;
    }
}

void video_draw_line(int x0, int y0, int x1, int y1, uint16_t color) {
    int dx = (x1 >= x0) ? (x1 - x0) : (x0 - x1);
    int sx = (x0 < x1) ? 1 : -1;
    int dy = (y1 >= y0) ? (y0 - y1) : (y1 - y0);
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx + dy;

    while (1) {
        video_draw_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) {
            err += dy;
            x0 += sx;
        }
        if (e2 <= dx) {
            err += dx;
            y0 += sy;
        }
    }
}

void video_draw_char(int x, int y, char c, uint16_t color, int scale) {
    uint8_t uc = (uint8_t)c;
    if (uc < 32 || uc > 126) return;
    const uint8_t *glyph = FONT_8X8[uc - 32];
    for (int r = 0; r < 8; r++) {
        uint8_t row = glyph[r];
        for (int col = 0; col < 8; col++) {
            if (row & (0x80 >> col)) {
                video_fill_rect(x + col * scale, y + r * scale, scale, scale, color);
            }
        }
    }
}

void video_draw_string(int x, int y, const char *str, uint16_t color, int scale) {
    if (!str) return;
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            y += 8 * scale + 2;
            cx = x;
            str++;
            continue;
        }
        video_draw_char(cx, y, *str++, color, scale);
        cx += 8 * scale;
    }
}

void video_draw_string_centered(int center_x, int y, const char *str, uint16_t color, int scale) {
    if (!str) return;
    int len = 0;
    const char *p = str;
    while (*p++) len++;
    int total_w = len * 8 * scale;
    int start_x = center_x - (total_w / 2);

    int cx = start_x;
    while (*str) {
        video_draw_char(cx, y, *str++, color, scale);
        cx += 8 * scale;
    }
}

static char hex_digit(uint8_t value) {
    return value < 10 ? (char)('0' + value) : (char)('A' + value - 10);
}

void video_draw_hex32(int x, int y, uint32_t value, uint16_t color, int scale) {
    char text[9];
    for (int i = 0; i < 8; ++i) {
        text[i] = hex_digit((uint8_t)(value >> (28 - i * 4)) & 0x0F);
    }
    text[8] = 0;
    video_draw_string(x, y, text, color, scale);
}

void video_draw_hex8(int x, int y, const uint8_t *data, uint16_t color, int scale) {
    if (!data) return;
    int cx = x;
    for (int i = 0; i < 8; ++i) {
        video_draw_char(cx, y, hex_digit(data[i] >> 4), color, scale);
        video_draw_char(cx + 8 * scale, y, hex_digit(data[i] & 0x0F), color, scale);
        cx += 24 * scale;
    }
}
