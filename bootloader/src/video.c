void video_init(void) {
    PVR_VIDEO_CFG     = 0x00000008;
    PVR_BORDER_COLOR  = 0x00000000;

    PVR_BORDER_X      = 0x007E0345;
    PVR_BORDER_Y      = 0x00240204;
    PVR_SCAN_CLK      = 0x020C0359;
    PVR_IL_CFG        = 0x00000100;
    PVR_BITMAP_X      = 0x000000AC;
    PVR_BITMAP_Y      = 0x00280028;
    PVR_SCALER_CFG    = 0x00000400;

    PVR_FB_ADDR       = 0x00000000;
    PVR_FB_IL_ADDR    = 0x00000000;
    PVR_FB_CFG_1      = 0x00800005;
    PVR_FB_CFG_2      = 0x00000009;
    PVR_RENDER_MODULO = 160;
    PVR_FB_SIZE       = (1 << 20) | (479 << 10) | 319;

    PVR_VIDEO_CFG     = 0x00000000;
}

void video_wait_vblank(void) {
    volatile uint32_t timeout = 1000000;
    while (!(PVR_SYNC_STATUS & 0x01FF) && --timeout != 0) { }
    timeout = 1000000;
    while ((PVR_SYNC_STATUS & 0x01FF) && --timeout != 0) { }
}

void video_wait_seconds(int seconds) {
    int total_vblanks = seconds * 60;
    for (int i = 0; i < total_vblanks; i++) {
        video_wait_vblank();
    }
}

void video_clear(uint16_t color) {
    volatile uint16_t *fb = (volatile uint16_t *)VRAM_BASE;
    for (int i = 0; i < SCREEN_WIDTH * SCREEN_HEIGHT; i++) {
        fb[i] = color;
    }
}

void video_fill_rect(int x, int y, int w, int h, uint16_t color) {
    volatile uint16_t *fb = (volatile uint16_t *)VRAM_BASE;
    for (int row = y; row < y + h; row++) {
        if ((unsigned)row >= SCREEN_HEIGHT) continue;
        volatile uint16_t *line = fb + (row * SCREEN_WIDTH) + x;
        for (int col = 0; col < w; col++) {
            if ((unsigned)(x + col) >= SCREEN_WIDTH) continue;
            line[col] = color;
        }
    }
}

void video_draw_char(int x, int y, char c, uint16_t color, int scale) {
    uint8_t uc = (uint8_t)c;
    if (uc < 32 || uc > 126) return;
    const uint8_t *glyph = FONT_8X8[uc - 32];
    for (int r = 0; r < 8; r++) {
        uint8_t row = glyph[r];
        for (int col = 0; col < 8; col++) {
            if (row & (0x80 >> col)) {
                video_fill_rect(x + col * scale, y + r * scale, scale, scale, color);
            }
        }
    }
}

void video_draw_string(int x, int y, const char *str, uint16_t color, int scale) {
    if (!str) return;
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            y += 8 * scale + 2;
            cx = x;
            str++;
            continue;
        }
        video_draw_char(cx, y, *str++, color, scale);
        cx += 8 * scale;
    }
}

void video_draw_string_centered(int center_x, int y, const char *str, uint16_t color, int scale) {
    if (!str) return;
    int len = 0;
    const char *p = str;
    while (*p++) len++;
    int total_w = len * 8 * scale;
    int start_x = center_x - (total_w / 2);

    int cx = start_x;
    while (*str) {
        video_draw_char(cx, y, *str++, color, scale);
        cx += 8 * scale;
    }
}

static char hex_digit(uint8_t value) {
    return value < 10 ? (char)('0' + value) : (char)('A' + value - 10);
}

void video_draw_hex32(int x, int y, uint32_t value, uint16_t color, int scale) {
    char text[9];
    for (int i = 0; i < 8; ++i) {
        text[i] = hex_digit((uint8_t)(value >> (28 - i * 4)) & 0x0F);
    }
    text[8] = 0;
    video_draw_string(x, y, text, color, scale);
}

void video_draw_hex8(int x, int y, const uint8_t *data, uint16_t color, int scale) {
    if (!data) return;
    int cx = x;
    for (int i = 0; i < 8; ++i) {
        video_draw_char(cx, y, hex_digit(data[i] >> 4), color, scale);
        video_draw_char(cx + 8 * scale, y, hex_digit(data[i] & 0x0F), color, scale);
        cx += 24 * scale;
    }
}
