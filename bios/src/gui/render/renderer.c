void renderer_set_fb(uint16_t *fb) {
    s_fb = fb;
}

void draw_rect(int x, int y, int w, int h, uint16_t color) {
    if(!s_fb) return;
    if(x < 0) { w += x; x = 0; }
    if(y < 0) { h += y; y = 0; }
    if(x + w > SCREEN_W) w = SCREEN_W - x;
    if(y + h > SCREEN_H) h = SCREEN_H - y;
    if(w <= 0 || h <= 0) return;

    for(int j = 0; j < h; j++) {
        uint16_t *row = &s_fb[(y + j) * SCREEN_W + x];
        for(int i = 0; i < w; i++) {
            row[i] = color;
        }
    }
}

