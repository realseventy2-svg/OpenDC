void draw_sysfont_char(int x, int y, char c, uint16_t color) {
    if(c < 32 || c > 126 || !s_fb) return;
    if(c == 32) return;

    const uint8_t *glyph = FONT_8X8[(uint8_t)c - 32];
    for(int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        int py = y + row;
        if(py >= 0 && py < SCREEN_H) {
            uint16_t *line = &s_fb[py * SCREEN_W];
            for(int col = 0; col < 8; col++) {
                if(bits & (0x80 >> col)) {
                    int px = x + col;
                    if(px >= 0 && px < SCREEN_W) line[px] = color;
                }
            }
        }
    }
}

void draw_sysfont_char_2x(int x, int y, char c, uint16_t color) {
    if(c < 32 || c > 126 || !s_fb) return;
    if(c == 32) return;

    const uint8_t *glyph = FONT_8X8[(uint8_t)c - 32];
    for(int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        int py1 = y + (row * 2);
        int py2 = py1 + 1;

        if(py1 >= 0 && py1 < SCREEN_H) {
            uint16_t *line1 = &s_fb[py1 * SCREEN_W];
            uint16_t *line2 = (py2 < SCREEN_H) ? &s_fb[py2 * SCREEN_W] : NULL;

            for(int col = 0; col < 8; col++) {
                if(bits & (0x80 >> col)) {
                    int px1 = x + (col * 2);
                    int px2 = px1 + 1;

                    if(px1 >= 0 && px1 < SCREEN_W) line1[px1] = color;
                    if(px2 >= 0 && px2 < SCREEN_W) line1[px2] = color;
                    if(line2) {
                        if(px1 >= 0 && px1 < SCREEN_W) line2[px1] = color;
                        if(px2 >= 0 && px2 < SCREEN_W) line2[px2] = color;
                    }
                }
            }
        }
    }
}

